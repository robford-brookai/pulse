class TestHandleTicketUpdated:
    @pytest.mark.asyncio
    async def test_valid_transition_updates_and_publishes(self):
        """Legal transition (open->in_progress) updates DB and publishes ticket.updated."""
        from src.handlers.tickets import handle_ticket_updated

        session = AsyncMock()
        # Mock the SELECT to return current status
        status_result = MagicMock()
        status_result.scalar_one_or_none.return_value = "open"
        session.execute = AsyncMock(return_value=status_result)
        producer = AsyncMock()
        event = _make_ticket_updated_event(new_status="in_progress")

        await handle_ticket_updated(event, session, producer=producer)

        assert producer.publish.called
        pub_event = producer.publish.call_args[0][1]
        assert pub_event["event_type"] == "ticket.updated"

    @pytest.mark.asyncio
    async def test_illegal_transition_skips(self):
        """Illegal transition (resolved->open) does not publish."""
        from src.handlers.tickets import handle_ticket_updated

        session = AsyncMock()
        status_result = MagicMock()
        status_result.scalar_one_or_none.return_value = "resolved"
        session.execute = AsyncMock(return_value=status_result)
        producer = AsyncMock()
        event = _make_ticket_updated_event(new_status="open")

        await handle_ticket_updated(event, session, producer=producer)

        producer.publish.assert_not_called()

    @pytest.mark.asyncio
    async def test_resolved_publishes_ticket_resolved(self):
        """Transition to 'resolved' publishes ticket.updated, ticket.resolved and outcome.recorded."""
        from src.handlers.tickets import handle_ticket_updated

        session = AsyncMock()
        status_result = MagicMock()
        status_result.scalar_one_or_none.return_value = "in_progress"
        session.execute = AsyncMock(return_value=status_result)
        producer = AsyncMock()
        event = _make_ticket_updated_event(new_status="resolved")

        await handle_ticket_updated(event, session, producer=producer)

        # Resolution dual-publishes: the ticket pair, plus outcome.recorded to ocean.outcomes
        # (phase 22 wired every resolution path through build_outcome_event).
        assert producer.publish.call_count == 3
        event_types = [c[0][1]["event_type"] for c in producer.publish.call_args_list]
        assert "ticket.updated" in event_types
        assert "ticket.resolved" in event_types
        assert "outcome.recorded" in event_types
        outcome_topic = next(
            c[0][0] for c in producer.publish.call_args_list if c[0][1]["event_type"] == "outcome.recorded"
        )
        assert outcome_topic == "ocean.outcomes"

