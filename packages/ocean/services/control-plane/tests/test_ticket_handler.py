    @pytest.mark.asyncio
    async def test_links_tasks_via_bridge_table(self):
        """When task_ids provided, INSERT INTO ticket_tasks for each."""
        from src.handlers.tickets import handle_ticket_created

        session = AsyncMock()
        session.execute = AsyncMock(return_value=_mock_sequence_result(1))
        producer = AsyncMock()
        event = _make_ticket_created_event(task_ids=["task-1", "task-2"])

        await handle_ticket_created(event, session, producer=producer)

        # 1 seq + 1 ticket INSERT + 2 ticket_tasks INSERTs = 4
        assert session.execute.call_count >= 4
        # Check that task_id params were passed for bridge inserts
        all_params = [c[0][1] for c in session.execute.call_args_list if len(c[0]) > 1]
        task_id_params = [p.get("task_id") for p in all_params if "task_id" in p]
        assert "task-1" in task_id_params
        assert "task-2" in task_id_params

